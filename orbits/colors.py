# ---------------------------------------------------------------- color math
def _rgb(hex_):
    c = Gdk.RGBA()
    c.parse(hex_)
    return c.red, c.green, c.blue


def _luminance(hex_):
    def ch(v):
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (ch(v) for v in _rgb(hex_))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast_fg(hex_):
    """White or near-black, whichever reads better on hex_."""
    return "#ffffff" if _luminance(hex_) < 0.40 else "rgb(0 0 6 / 80%)"


# ---------------------------------------------------------------- CSS generation
def _declarations(colors, legacy=False):
    out = []
    for role in ROLE_ORDER:
        value = colors.get(role)
        if not value:
            continue
        _label, variables, names = ROLES[role]
        for v in (names if legacy else variables):
            out.append(f"@define-color {v} {value};" if legacy else f"  --{v}: {value};")
    for bg, fgs in (("accent", ("accent-fg-color",) if not legacy else ("accent_fg_color",)),
                    ("destructive", ("destructive-fg-color",) if not legacy else ("destructive_fg_color",))):
        if colors.get(bg):
            for v in fgs:
                fg = contrast_fg(colors[bg])
                out.append(f"@define-color {v} {fg};" if legacy else f"  --{v}: {fg};")
    return out


def gtk4_css(palette):
    parts = [MARKER, ""]
    if palette.get("light"):
        parts += [":root {", *_declarations(palette["light"]), "}", ""]
    if palette.get("dark"):
        parts += ["@media (prefers-color-scheme: dark) {", "  :root {",
                  *("  " + d for d in _declarations(palette["dark"])), "  }", "}", ""]
    return "\n".join(parts)


def gtk3_css(palette, dark):
    variant = palette.get("dark" if dark else "light")
    if not variant:
        return None
    return "\n".join([MARKER, f"/* {'dark' if dark else 'light'} variant — Orbits rewrites this when the style "
                              "changes */", *_declarations(variant, legacy=True), ""])


def preview_css(selector, variant):
    """CSS that scopes a palette variant to one widget subtree (custom properties inherit)."""
    decl = _declarations(variant or {})
    return (f"{selector} {{\n" + "\n".join(decl) + "\n  background-color: var(--window-bg-color);\n"
            "  color: var(--window-fg-color);\n}\n")


# ---------------------------------------------------------------- state
def load_state():
    try:
        return json.loads(STATE.read_text())
    except (OSError, ValueError):
        return {"preset": "Nord", "palette": PRESETS["Nord"], "gtk3": False, "flatpak": False, "applied": False}


def save_state(state):
    STATE.write_text(json.dumps(state, indent=2))


def _ours(path: Path):
    try:
        return not path.is_symlink() and path.read_text(errors="ignore").startswith(MARKER)
    except OSError:
        return False


def gtk4_conflict():
    """Describe what's in ~/.config/gtk-4.0/gtk.css if it isn't ours (theme link or a hand-written file)."""
    f = GTK4 / "gtk.css"
    if f.is_symlink():
        return "link", os.readlink(f)
    if f.exists() and not _ours(f):
        return "file", str(f)
    return None, None


def _write(path: Path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        path.unlink()
    elif path.exists() and not _ours(path):
        backup = path.parent / "orbits-backup"
        backup.mkdir(exist_ok=True)
        dest = backup / path.name
        if dest.exists():
            dest = backup / f"{path.name}.{int(time.time())}"
        shutil.move(str(path), dest)
    tmp = path.with_suffix(".orbits-tmp")
    tmp.write_text(text)
    os.replace(tmp, path)


def _remove(path: Path):
    if _ours(path):
        path.unlink()
        backup = path.parent / "orbits-backup" / path.name
        if backup.exists():
            shutil.move(str(backup), path)


def prefers_dark():
    return Gio.Settings.new("org.gnome.desktop.interface").get_string("color-scheme") == "prefer-dark"


def apply(state):
    """Write the stylesheets for state['palette'] and persist it. Returns notes for the user."""
    notes = []
    kind, _target = gtk4_conflict()
    if kind == "link":
        from orbits import themes

        themes.remove_libadwaita()
        notes.append("Replaced the GTK4 theme link with your colors")
    _write(GTK4 / "gtk.css", gtk4_css(state["palette"]))
    if state.get("gtk3"):
        css = gtk3_css(state["palette"], prefers_dark())
        if css:
            _write(GTK3 / "gtk.css", css)
        else:
            _remove(GTK3 / "gtk.css")
    else:
        _remove(GTK3 / "gtk.css")
    want = bool(state.get("flatpak"))
    if want != bool(state.get("flatpak_applied")):
        set_flatpak(want)
        state["flatpak_applied"] = want
    state["applied"] = True
    save_state(state)
    return notes


def remove():
    state = load_state()
    _remove(GTK4 / "gtk.css")
    _remove(GTK3 / "gtk.css")
    if state.get("flatpak_applied"):
        set_flatpak(False)
        state["flatpak_applied"] = False
    state["applied"] = False
    save_state(state)


def is_applied():
    return _ours(GTK4 / "gtk.css")


def refresh_gtk3_for_scheme():
    """GTK3 can't switch palettes by itself; call when the color scheme changes."""
    state = load_state()
    if state.get("applied") and state.get("gtk3") and _ours(GTK3 / "gtk.css"):
        css = gtk3_css(state["palette"], prefers_dark())
        if css:
            _write(GTK3 / "gtk.css", css)


def set_flatpak(enabled):
    """Let Flatpak apps read ~/.config/gtk-4.0 and gtk-3.0 (read-only), or revoke it again."""
    if not shutil.which("flatpak"):
        return
    paths = ["xdg-config/gtk-4.0:ro", "xdg-config/gtk-3.0:ro"]
    args = [f"--filesystem={p}" for p in paths] if enabled else \
        [f"--nofilesystem={p.split(':')[0]}" for p in paths]
    subprocess.run(["flatpak", "override", "--user", *args], check=False,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
